const languageButtons = document.querySelectorAll("[data-lang]");
const languagePreference = "forno-lume-editorial-lang";
const translatedText = document.querySelectorAll("[data-i18n]");
const translatedLabels = document.querySelectorAll("[data-i18n-label]");
const translatedAlts = document.querySelectorAll("[data-i18n-alt]");
const prices = document.querySelectorAll("[data-price]");
const timeRanges = document.querySelectorAll(".hours dd");
const metadata = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const dictionary = translations[language];
  const euro = new Intl.NumberFormat(dictionary.locale, {
    style: "currency",
    currency: "EUR",
  });

  document.documentElement.lang = language;
  document.title = dictionary.title;
  metadata.content = dictionary.metaDescription;
  translatedText.forEach((element) => {
    element.textContent = dictionary[element.dataset.i18n];
  });
  translatedLabels.forEach((element) => {
    element.setAttribute("aria-label", dictionary[element.dataset.i18nLabel]);
  });
  translatedAlts.forEach((element) => {
    element.alt = dictionary[element.dataset.i18nAlt];
  });
  prices.forEach((price) => {
    price.textContent = euro.format(Number(price.dataset.price));
  });
  timeRanges.forEach((range) => {
    const separator = language === "sl" ? "." : ":";
    range.textContent = range.textContent.replace(/[.:]/g, separator);
  });
  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
    try {
      localStorage.setItem(languagePreference, button.dataset.lang);
    } catch {
      // Language switching still works when browser storage is unavailable.
    }
  });
});

try {
  const savedLanguage = localStorage.getItem(languagePreference);
  if (Object.hasOwn(translations, savedLanguage)) setLanguage(savedLanguage);
} catch {
  // The page already contains Slovenian content.
}

const filters = document.querySelector(".filters");
const filterButtons = filters.querySelectorAll("[data-filter]");
const menuGroups = document.querySelector(".menu-groups");
const categories = menuGroups.querySelectorAll("[data-category]");

filters.hidden = false;
filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const { filter } = button.dataset;
    menuGroups.dataset.filter = filter;
    filterButtons.forEach((item) => {
      item.setAttribute("aria-pressed", String(item === button));
    });
    categories.forEach((category) => {
      category.hidden = filter !== "all" && category.dataset.category !== filter;
    });
  });
});

const dishDialog = document.querySelector("#dishModal");
const dishTitle = document.querySelector("#dishModalTitle");
const dishCategory = document.querySelector("#dishModalCategory");
const dishText = document.querySelector("#dishModalText");
const dishPrice = document.querySelector("#dishModalPrice");
const dishFigure = dishDialog.querySelector("figure");
const dishImage = document.createElement("img");
dishImage.alt = "";

document.querySelectorAll(".menu-line").forEach((line) => {
  line.addEventListener("click", () => {
    dishTitle.textContent = line.querySelector(".dish-name").textContent;
    dishCategory.textContent = line.closest(".menu-group").querySelector("h3").textContent;
    dishText.textContent = line.querySelector(".dish-description").textContent;
    dishPrice.textContent = line.querySelector(".dish-price").textContent;
    dishImage.src = line.querySelector(".dish-thumb").getAttribute("src");
    dishFigure.hidden = false;
    dishFigure.prepend(dishImage);
    dishDialog.showModal();
  });
});

const bookingDialog = document.querySelector("#bookingModal");
const bookingTrigger = document.querySelector("#bookingTrigger");
const bookingForm = document.querySelector("#bookingForm");
const guestCount = document.querySelector("#guestCount");
const bookingSlot = document.querySelector("#bookingSlot");
const bookingSummary = document.querySelector("#bookingSummary");

bookingTrigger.hidden = false;
bookingTrigger.addEventListener("click", () => {
  bookingForm.reset();
  bookingSummary.textContent = "";
  bookingDialog.showModal();
});

bookingForm.addEventListener("change", () => {
  bookingSummary.textContent = "";
});

bookingForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const dictionary = translations[document.documentElement.lang];
  bookingSummary.textContent = dictionary.bookingSummary(guestCount.value, dictionary[bookingSlot.value]);
});
